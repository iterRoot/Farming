using AutoMapper;

namespace FarmingApi.Modules.Inventory.DutyGroups;

public class DutyGroupMapper : Profile
{
    public DutyGroupMapper()
    {
        CreateMap<DutyGroup, DutyGroupResponse>();
        CreateMap<DutyGroupRequest, DutyGroup>()
            .ForMember(d => d.Id,        opt => opt.Ignore())
            .ForMember(d => d.CreatedAt, opt => opt.Ignore())
            .ForMember(d => d.UpdatedAt, opt => opt.Ignore())
            .ForMember(d => d.InActive,  opt => opt.Ignore());
    }
}
