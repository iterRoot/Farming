using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using FarmingApi.Core;
using FarmingApi.Modules.Financials.ChartOfAccounts;
using FarmingApi.Modules.Financials.JournalEntry;

namespace FarmingApi.Modules.Banking.InternalTransfer;

// ═══════════════════════════════════════════════════════════════════
// INTERNAL TRANSFER  (route: /InternalTransfer)
// GET    /InternalTransfer             → all transfers (?account, ?status)
// GET    /InternalTransfer/{id}
// POST   /InternalTransfer             → validates and posts the journal entry
// POST   /InternalTransfer/{id}/Void   → voids the journal entry (reverses the GL)
// There is no edit: a posted transfer is corrected by voiding it and entering a new one.
// ═══════════════════════════════════════════════════════════════════
public class InternalTransferController : MyController
{
    private readonly IInternalTransferRepository _repository;
    private readonly MyDbContext                 _db;

    public InternalTransferController(IInternalTransferRepository repository, MyDbContext db)
    {
        _repository = repository;
        _db         = db;
    }

    [HttpGet]
    public IActionResult Gets([FromQuery] string? account = null, [FromQuery] string? status = null)
    {
        var query = _repository.GetAll().AsQueryable();
        if (!string.IsNullOrEmpty(account)) query = query.Where(t => t.FromAccount == account || t.ToAccount == account);
        if (!string.IsNullOrEmpty(status))  query = query.Where(t => t.Status == status);
        return Ok(query.OrderByDescending(t => t.PostingDate).ThenByDescending(t => t.Id).ToList().Select(ToResponse).ToList());
    }

    [HttpGet("{id:int}")]
    public IActionResult Get(int id)
    {
        var t = _repository.GetSingle(x => x.Id == id);
        return t == null ? NotFound($"Internal transfer {id} not found") : Ok(ToResponse(t));
    }

    [HttpPost]
    public IActionResult Create([FromBody] InternalTransferRequest r)
    {
        if (r.PostingDate == default) return BadRequest("Enter the transfer date.");
        if (string.IsNullOrWhiteSpace(r.FromAccount) || string.IsNullOrWhiteSpace(r.ToAccount))
            return BadRequest("Choose the account the money leaves and the account it goes to.");
        if (r.FromAccount.Trim() == r.ToAccount.Trim()) return BadRequest("The from and to accounts must be different.");
        if (r.Amount <= 0) return BadRequest("The amount must be more than zero.");
        if (r.BankCharge < 0) return BadRequest("The bank charge cannot be negative.");

        var accounts = _db.Set<ChartOfAccounts>().AsNoTracking();
        string? Check(string code, string role, out ChartOfAccounts? acct)
        {
            acct = accounts.FirstOrDefault(a => a.AcctCode == code.Trim());
            if (acct == null) return $"{role} account '{code.Trim()}' is not in the chart of accounts.";
            if (!acct.AllowPosting) return $"{role} account {acct.AcctCode} does not allow posting.";
            if (!acct.IsActive) return $"{role} account {acct.AcctCode} is inactive.";
            return null;
        }
        var fromErr = Check(r.FromAccount, "From", out var from);
        var toErr   = Check(r.ToAccount, "To", out var to);
        var err     = fromErr ?? toErr;
        ChartOfAccounts? charge = null;
        if (err == null && r.BankCharge > 0)
        {
            if (string.IsNullOrWhiteSpace(r.ChargeAccount)) err = "Choose the account to post the bank charge to.";
            else err = Check(r.ChargeAccount, "Bank charge", out charge);
        }
        if (err != null) return BadRequest(err);

        var docNum = GenerateDocNum(r.PostingDate);
        var memo = string.IsNullOrWhiteSpace(r.Memo)
            ? $"Internal transfer {docNum}: {from!.AcctCode} → {to!.AcctCode}"
            : r.Memo.Trim();

        using var tx = _db.Database.BeginTransaction();
        try
        {
            var total = r.Amount + r.BankCharge;
            var je = new JournalEntry
            {
                JrnlNo          = JournalEntryNumberService.Next(_db, r.PostingDate),
                TransDate       = r.PostingDate,
                DueDate         = r.PostingDate,
                DocDate         = r.PostingDate,
                RefNo           = docNum,
                Ref2            = r.Reference?.Trim(),
                Memo            = memo,
                TransType       = "KBIT",
                BaseDocType     = "KBIT",
                Currency        = string.IsNullOrWhiteSpace(r.Currency) ? "USD" : r.Currency,
                ExchangeRate    = 1,
                Status          = "O",
                IsAutoGenerated = true,
                VersionNum      = 1,
                TotalDebit      = total,
                TotalCredit     = total,
                TotalLC         = total,
                TotalFC         = total,
                CreatedAt       = DateTime.UtcNow,
                InActive        = false,
            };
            int n = 1;
            je.Lines.Add(JeLine(n++, to!.AcctCode, to.AcctName, r.Amount, 0, memo));
            if (r.BankCharge > 0)
                je.Lines.Add(JeLine(n++, charge!.AcctCode, charge.AcctName, r.BankCharge, 0, $"Bank charge — {docNum}"));
            je.Lines.Add(JeLine(n++, from!.AcctCode, from.AcctName, 0, total, memo));

            _db.Set<JournalEntry>().Add(je);
            _db.SaveChanges();

            var entity = new InternalTransfer
            {
                DocNum = docNum, PostingDate = r.PostingDate,
                FromAccount = from.AcctCode, FromAccountName = from.AcctName,
                ToAccount = to.AcctCode, ToAccountName = to.AcctName,
                Amount = r.Amount, BankCharge = r.BankCharge, ChargeAccount = charge?.AcctCode,
                Currency = je.Currency, Reference = r.Reference?.Trim(), Memo = r.Memo?.Trim(),
                Status = "P", JournalEntryId = je.Id, JournalNo = je.JrnlNo,
                CreatedAt = DateTime.UtcNow, InActive = false,
            };
            _repository.Add(entity);
            _db.SaveChanges();

            je.BaseDocEntry = entity.Id;
            _db.SaveChanges();

            tx.Commit();
            return Ok(new { message = $"Transfer {docNum} posted as {je.JrnlNo}", id = entity.Id, docNum, journalEntryId = je.Id, journalNo = je.JrnlNo });
        }
        catch (Exception ex)
        {
            tx.Rollback();
            return BadRequest(ex.InnerException?.Message ?? ex.Message);
        }
    }

    [HttpPost("{id:int}/Void")]
    public IActionResult Void(int id)
    {
        var t = _repository.GetSingle(x => x.Id == id);
        if (t == null) return NotFound();
        if (t.Status == "V") return BadRequest($"Transfer {t.DocNum} is already void.");

        var je = t.JournalEntryId == null ? null : _db.Set<JournalEntry>().FirstOrDefault(j => j.Id == t.JournalEntryId);
        if (je != null && je.Status != "V")
        {
            je.Status    = "V";   // GLBalanceSync reverses the account balances on save
            je.UpdatedAt = DateTime.UtcNow;
        }
        t.Status    = "V";
        t.UpdatedAt = DateTime.UtcNow;
        _db.SaveChanges();
        return Ok(new { message = $"Transfer {t.DocNum} voided" });
    }

    private static JournalEntryLine JeLine(int n, string code, string name, decimal dr, decimal cr, string memo) => new()
    {
        LineNum = n, AccountCode = code, AccountName = name,
        Debit = dr, Credit = cr, DebitLC = dr, CreditLC = cr,
        LineMemo = memo, CreatedAt = DateTime.UtcNow, InActive = false,
    };

    private string GenerateDocNum(DateTime date)
    {
        var prefix = $"IT-{date.Year}-";
        var last = _repository.GetAll().Where(t => t.DocNum.StartsWith(prefix)).OrderByDescending(t => t.Id).FirstOrDefault();
        if (last == null) return $"{prefix}00001";
        var parts = last.DocNum.Split('-');
        return parts.Length >= 3 && int.TryParse(parts[2], out int n) ? $"{prefix}{n + 1:D5}" : $"{prefix}00001";
    }

    private static InternalTransferResponse ToResponse(InternalTransfer t) => new()
    {
        Id = t.Id, DocNum = t.DocNum, PostingDate = t.PostingDate,
        FromAccount = t.FromAccount, FromAccountName = t.FromAccountName,
        ToAccount = t.ToAccount, ToAccountName = t.ToAccountName,
        Amount = t.Amount, BankCharge = t.BankCharge, ChargeAccount = t.ChargeAccount,
        Currency = t.Currency, Reference = t.Reference, Memo = t.Memo, Status = t.Status,
        JournalEntryId = t.JournalEntryId, JournalNo = t.JournalNo,
        CreatedAt = t.CreatedAt, UpdatedAt = t.UpdatedAt,
    };
}
