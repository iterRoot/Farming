using KamnttraApi.Modules.Financials.GLAccountDetermination;
using KamnttraApi.Modules.Financials.JournalEntry;
using GRPOLine = KamnttraApi.Modules.PurchaseAP.GoodsReceiptPO.GoodsReceiptPOLine;
using BPEntity = KamnttraApi.Modules.BusinessPartners.BusinessPartnersMaster.BusinessPartnersMaster;

namespace KamnttraApi.Modules.PurchaseAP.APInvoice;

public interface IAPInvoiceJournalService
{
    JournalEntry CreateJournalEntry(APInvoice invoice, BPEntity vendor);
}

public class APInvoiceJournalService : IAPInvoiceJournalService
{
    private readonly MyDbContext _db;

    private readonly GLAccountResolver _resolver;

    public APInvoiceJournalService(MyDbContext db, GLAccountResolver resolver)
    {
        _db = db;
        _resolver = resolver;
    }

    public JournalEntry CreateJournalEntry(APInvoice invoice, BPEntity vendor)
    {
        var gl = _db.Set<GLAccountDetermination>().FirstOrDefault()
                 ?? throw new InvalidOperationException(
                     "GL Account Determination (KGLD) not configured. " +
                     "Go to Administration → GL Account Determination and add " +
                     "AccountsPayable, PurchaseExpense, PurchaseTax.");

        var payableCode = _resolver.ForBpGroup("AccountsPayable", vendor.GroupCode, gl.AccountsPayable);
        var taxCode     = gl.PurchaseTax;

        if (string.IsNullOrWhiteSpace(payableCode))
            throw new InvalidOperationException(
                "Accounts Payable account not set in GL Account Determination (KGLD).");

        var grandTotal = invoice.Total;
        var taxAmount  = invoice.TaxAmount;
        var netExpense = grandTotal - taxAmount;

        if (grandTotal <= 0)
            throw new InvalidOperationException(
                $"Cannot post AP Invoice {invoice.DocNum}: total is {grandTotal}");

        var postingDate = invoice.PostingDate ?? DateTime.UtcNow;

        var je = new JournalEntry
        {
            JrnlNo          = JournalEntryNumberService.Next(_db, postingDate),
            TransDate       = postingDate,
            DueDate         = invoice.DueDate ?? postingDate,
            DocDate         = postingDate,
            RefNo           = invoice.DocNum,
            Memo            = $"AP Invoice {invoice.DocNum} - {vendor.CardName}",
            TransType       = "APIN",
            BaseDocEntry    = invoice.Id,
            BaseDocType     = "KPI",
            Currency        = "USD",
            ExchangeRate    = 1,
            TotalDebit      = 0,
            TotalCredit     = 0,
            TotalFC         = 0,
            TotalLC         = 0,
            Status          = "O",
            IsAutoGenerated = true,
            VersionNum      = 1,
            CreatedAt       = DateTime.UtcNow,
            InActive        = false,
        };

        int lineNum = 1;

        // An AP invoice records a purchase and the payable owed to the vendor.
        // Dr, net of tax, per line: GR/IR clearing for lines already received on a Goods
        // Receipt PO, Inventory for stock items this invoice brings into stock, and
        // Purchase Expense for services and non-stock items.
        RefuseGoodsAlreadyReserveInvoiced(invoice);

        // Received lines clear GR/IR at the receipt's value; a different invoice price goes to Price Difference.
        var accounts = new PurchaseLineAccounts(_db, _resolver);
        var items    = accounts.Items(invoice.Items.Select(l => l.ItemCode));
        var received = accounts.ReceiptUnitValues(invoice.Items.Where(IsBasedOnGoodsReceipt).Select(l => l.BaseEntry));
        var lines    = invoice.Items.Select(l => new PurchaseLine(l.ItemCode, l.Quantity, l.Price, l.Total,
            PurchaseLineAccounts.RoleOf(l.ItemCode != null && items.TryGetValue(l.ItemCode, out var it) ? it : null,
                IsBasedOnGoodsReceipt(l), PurchaseLineRole.Inventory),
            IsBasedOnGoodsReceipt(l) ? PurchaseLineAccounts.ClearingValueOf(received, l.BaseEntry, l.ItemCode, l.Quantity) : null)).ToList();
        PurchaseLineAccounts.AddLines(je, accounts.Split(gl, netExpense, lines), debit: true, ref lineNum, invoice.DocNum);

        // Dr Input VAT — recoverable tax, only when there is tax
        if (taxAmount > 0)
        {
            if (string.IsNullOrWhiteSpace(taxCode))
                throw new InvalidOperationException(
                    "Invoice has tax but Purchase Tax (input VAT) account is not set in KGLD.");

            je.Lines.Add(new JournalEntryLine
            {
                LineNum     = lineNum++,
                AccountCode = taxCode,
                AccountName = "Input VAT",
                CardCode    = null,
                CardName    = null,
                Debit       = taxAmount,
                Credit      = 0,
                DebitLC     = taxAmount,
                CreditLC    = 0,
                DebitFC     = 0,
                CreditFC    = 0,
                LineMemo    = $"Input VAT — {invoice.DocNum}",
                TaxAmount   = taxAmount,
                CreatedAt   = DateTime.UtcNow,
                InActive    = false,
            });
        }

        // Cr Accounts Payable — full amount owed to the vendor (incl. tax)
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = payableCode,
            AccountName = "Accounts Payable",
            CardCode    = vendor.Code,
            CardName    = vendor.CardName,
            Debit       = 0,
            Credit      = grandTotal,
            DebitLC     = 0,
            CreditLC    = grandTotal,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Accounts Payable — {invoice.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        var totalDr = je.Lines.Sum(l => l.Debit);
        var totalCr = je.Lines.Sum(l => l.Credit);
        if (Math.Abs(totalDr - totalCr) > 0.01m)
            throw new InvalidOperationException(
                $"Journal entry unbalanced: Dr={totalDr:N2} Cr={totalCr:N2}. " +
                $"Check invoice Total ({grandTotal}) vs TaxAmount ({taxAmount}).");

        je.TotalDebit  = totalDr;
        je.TotalCredit = totalCr;
        je.TotalLC     = totalDr;
        je.TotalFC     = 0;

        _db.Set<JournalEntry>().Add(je);
        return je;
    }

    /// <summary>
    /// Goods received against an AP Reserve Invoice were billed, and put on the payable, by that
    /// invoice. Invoicing the receipt again would owe the vendor twice, so it is refused.
    /// </summary>
    private void RefuseGoodsAlreadyReserveInvoiced(APInvoice invoice)
    {
        var receiptIds = invoice.Items.Where(IsBasedOnGoodsReceipt).Select(l => l.BaseEntry!.Value).Distinct().ToList();
        if (receiptIds.Count == 0) return;

        var reserved = _db.Set<GRPOLine>()
            .Where(l => receiptIds.Contains(l.GoodsReceiptPOId) && l.BaseEntry != null
                        && l.BaseType != null && l.BaseType.ToUpper() == "APRESERVEINVOICE")
            .Select(l => new { l.GoodsReceiptPOId, l.ItemCode, l.GoodsReceiptPO.DocNum })
            .ToList();

        var hit = invoice.Items.Where(IsBasedOnGoodsReceipt)
            .Select(l => reserved.FirstOrDefault(r => r.GoodsReceiptPOId == l.BaseEntry && r.ItemCode == l.ItemCode))
            .FirstOrDefault(r => r != null);
        if (hit != null)
            throw new InvalidOperationException(
                $"Item {hit.ItemCode} on Goods Receipt PO {hit.DocNum} was received against an AP Reserve Invoice, " +
                "which already billed it. It can't be invoiced again.");
    }

    /// <summary>True when the line was copied from a Goods Receipt PO, whose receipt already moved the stock.</summary>
    public static bool IsBasedOnGoodsReceipt(APInvoiceLine line) =>
        line.BaseEntry.HasValue
        && string.Equals(line.BaseType, "GoodsReceiptPO", StringComparison.OrdinalIgnoreCase);
}
