using KamnttraApi.Modules.Financials.GLAccountDetermination;
using KamnttraApi.Modules.Financials.JournalEntry;
using BPEntity = KamnttraApi.Modules.BusinessPartners.BusinessPartnersMaster.BusinessPartnersMaster;

namespace KamnttraApi.Modules.PurchaseAP.APReserveInvoice;

public interface IAPReserveInvoiceJournalService
{
    JournalEntry CreateJournalEntry(APReserveInvoice reserveInvoice, BPEntity vendor);
}

public class APReserveInvoiceJournalService : IAPReserveInvoiceJournalService
{
    private readonly MyDbContext _db;
    private readonly GLAccountResolver _resolver;

    public APReserveInvoiceJournalService(MyDbContext db, GLAccountResolver resolver)
    {
        _db = db;
        _resolver = resolver;
    }

    public JournalEntry CreateJournalEntry(APReserveInvoice reserveInvoice, BPEntity vendor)
    {
        var gl = _db.Set<GLAccountDetermination>().FirstOrDefault()
                 ?? throw new InvalidOperationException(
                     "GL Account Determination (KGLD) not configured. " +
                     "Go to Administration → GL Account Determination and add " +
                     "AccountsPayable, PurchaseExpense, PurchaseTax.");

        var payableCode = gl.AccountsPayable;
        var taxCode     = gl.PurchaseTax;

        if (string.IsNullOrWhiteSpace(payableCode))
            throw new InvalidOperationException(
                "Accounts Payable account not set in GL Account Determination (KGLD).");

        var grandTotal = reserveInvoice.Total;
        var taxAmount  = reserveInvoice.TaxAmount;
        var netExpense = grandTotal - taxAmount;

        if (grandTotal <= 0)
            throw new InvalidOperationException(
                $"Cannot post AP Reserve Invoice {reserveInvoice.DocNum}: total is {grandTotal}");

        var postingDate = reserveInvoice.PostingDate ?? DateTime.UtcNow;

        var je = new JournalEntry
        {
            JrnlNo          = JournalEntryNumberService.Next(_db, postingDate),
            TransDate       = postingDate,
            DueDate         = reserveInvoice.DueDate ?? postingDate,
            DocDate         = postingDate,
            RefNo           = reserveInvoice.DocNum,
            Memo            = $"AP Reserve Invoice {reserveInvoice.DocNum} - {vendor.CardName}",
            TransType       = "APRI",
            BaseDocEntry    = reserveInvoice.Id,
            BaseDocType     = "KPRI",
            Currency        = "USD",
            ExchangeRate    = 1,
            TotalDebit      = 0,
            TotalCredit     = 0,
            TotalFC         = 0,
            TotalLC         = 0,
            Status          = "O",
            IsAutoGenerated = true,
            VersionNum      = 1,
            CreatedAt       = DateTime.UtcNow,
            InActive        = false,
        };

        int lineNum = 1;

        // An AP reserve invoice records a purchase and the payable owed to the vendor before the
        // goods arrive. Dr, net of tax, per line: GR/IR clearing for stock items (the Goods
        // Receipt PO that delivers them credits clearing), Purchase Expense for services and
        // non-stock items.
        var accounts = new PurchaseLineAccounts(_db, _resolver);
        var items    = accounts.Items(reserveInvoice.Items.Select(l => l.ItemCode));
        var lines    = reserveInvoice.Items.Select(l => new PurchaseLine(l.ItemCode, l.Quantity, l.Price, l.Total,
            PurchaseLineAccounts.RoleOf(l.ItemCode != null && items.TryGetValue(l.ItemCode, out var it) ? it : null,
                false, PurchaseLineRole.Clearing))).ToList();
        PurchaseLineAccounts.AddLines(je, accounts.Split(gl, netExpense, lines), debit: true, ref lineNum, reserveInvoice.DocNum);

        // Dr Input VAT — recoverable tax, only when there is tax
        if (taxAmount > 0)
        {
            if (string.IsNullOrWhiteSpace(taxCode))
                throw new InvalidOperationException(
                    "Invoice has tax but Purchase Tax (input VAT) account is not set in KGLD.");

            je.Lines.Add(new JournalEntryLine
            {
                LineNum     = lineNum++,
                AccountCode = taxCode,
                AccountName = "Input VAT",
                CardCode    = null,
                CardName    = null,
                Debit       = taxAmount,
                Credit      = 0,
                DebitLC     = taxAmount,
                CreditLC    = 0,
                DebitFC     = 0,
                CreditFC    = 0,
                LineMemo    = $"Input VAT — {reserveInvoice.DocNum}",
                TaxAmount   = taxAmount,
                CreatedAt   = DateTime.UtcNow,
                InActive    = false,
            });
        }

        // Cr Accounts Payable — full amount owed to the vendor (incl. tax)
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = payableCode,
            AccountName = "Accounts Payable",
            CardCode    = vendor.Code,
            CardName    = vendor.CardName,
            Debit       = 0,
            Credit      = grandTotal,
            DebitLC     = 0,
            CreditLC    = grandTotal,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Accounts Payable — {reserveInvoice.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        var totalDr = je.Lines.Sum(l => l.Debit);
        var totalCr = je.Lines.Sum(l => l.Credit);
        if (Math.Abs(totalDr - totalCr) > 0.01m)
            throw new InvalidOperationException(
                $"Journal entry unbalanced: Dr={totalDr:N2} Cr={totalCr:N2}. " +
                $"Check invoice Total ({grandTotal}) vs TaxAmount ({taxAmount}).");

        je.TotalDebit  = totalDr;
        je.TotalCredit = totalCr;
        je.TotalLC     = totalDr;
        je.TotalFC     = 0;

        _db.Set<JournalEntry>().Add(je);
        return je;
    }
}
