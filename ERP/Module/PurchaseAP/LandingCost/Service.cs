using FarmingApi.Modules.Financials.GLAccountDetermination;
using FarmingApi.Modules.Financials.JournalEntry;
using BPEntity = FarmingApi.Modules.BusinessPartners.BusinessPartnersMaster.BusinessPartnersMaster;

namespace FarmingApi.Modules.PurchaseAP.LandingCost;

public interface ILandedCostJournalService
{
    JournalEntry CreateJournalEntry(LandedCost landedCost, BPEntity vendor);
}

// Mirrors GoodsReceiptPOJournalService's own Dr-Inventory/Cr-clearing pattern:
// the extra cost capitalises straight into Inventory, offset against the
// landed-cost vendor (freight forwarder, customs agent...) the same way a
// GRPO offsets against the goods vendor before the AP invoice arrives.
public class LandedCostJournalService : ILandedCostJournalService
{
    private readonly MyDbContext _db;
    public LandedCostJournalService(MyDbContext db) { _db = db; }

    public JournalEntry CreateJournalEntry(LandedCost landedCost, BPEntity vendor)
    {
        var gl = _db.Set<GLAccountDetermination>().FirstOrDefault()
                 ?? throw new InvalidOperationException(
                     "GL Account Determination (KGLD) not configured. " +
                     "Go to Administration → GL Account Determination and add " +
                     "InventoryAccount and InventoryOffset.");

        var inventoryCode = gl.InventoryAccount;
        var offsetCode    = gl.InventoryOffset;

        if (string.IsNullOrWhiteSpace(inventoryCode))
            throw new InvalidOperationException("Inventory account not set in GL Account Determination (KGLD).");
        if (string.IsNullOrWhiteSpace(offsetCode))
            throw new InvalidOperationException("Inventory Offset (GR/IR clearing) account not set in GL Account Determination (KGLD).");

        var totalCost = landedCost.CostLines.Sum(c => c.Amount);
        if (totalCost <= 0)
            throw new InvalidOperationException($"Cannot post Landed Cost {landedCost.DocNum}: total is {totalCost}.");

        var postingDate = landedCost.PostingDate ?? landedCost.DocDate ?? DateTime.UtcNow;

        var je = new JournalEntry
        {
            JrnlNo          = JournalEntryNumberService.Next(_db, postingDate),
            TransDate       = postingDate,
            DueDate         = postingDate,
            DocDate         = landedCost.DocDate ?? postingDate,
            RefNo           = landedCost.DocNum,
            Memo            = $"Landed Cost {landedCost.DocNum} - {vendor.CardName}",
            TransType       = "LandedCost",
            BaseDocEntry    = landedCost.Id,
            BaseDocType     = "KLDC",
            Currency        = "USD",
            ExchangeRate    = 1,
            TotalDebit      = 0,
            TotalCredit     = 0,
            TotalFC         = 0,
            TotalLC         = 0,
            Status          = "O",
            IsAutoGenerated = true,
            VersionNum      = 1,
            CreatedAt       = DateTime.UtcNow,
            InActive        = false,
        };

        int lineNum = 1;

        // Dr Inventory — the extra cost capitalises into the goods already received
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = inventoryCode,
            AccountName = "Inventory",
            CardCode    = null,
            CardName    = null,
            Debit       = totalCost,
            Credit      = 0,
            DebitLC     = totalCost,
            CreditLC    = 0,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Landed cost allocated — {landedCost.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        // Cr Inventory Offset — payable to the vendor who billed the landed costs
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = offsetCode,
            AccountName = "GR/IR Clearing",
            CardCode    = vendor.Code,
            CardName    = vendor.CardName,
            Debit       = 0,
            Credit      = totalCost,
            DebitLC     = 0,
            CreditLC    = totalCost,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Landed cost clearing — {landedCost.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        var totalDr = je.Lines.Sum(l => l.Debit);
        var totalCr = je.Lines.Sum(l => l.Credit);
        if (Math.Abs(totalDr - totalCr) > 0.01m)
            throw new InvalidOperationException($"Journal entry unbalanced: Dr={totalDr:N2} Cr={totalCr:N2} for {landedCost.DocNum}.");

        je.TotalDebit  = totalDr;
        je.TotalCredit = totalCr;
        je.TotalLC     = totalDr;
        je.TotalFC     = 0;

        _db.Set<JournalEntry>().Add(je);
        return je;
    }
}
