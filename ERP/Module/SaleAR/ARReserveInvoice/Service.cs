using FarmingApi.Modules.Financials.GLAccountDetermination;
using FarmingApi.Modules.Financials.JournalEntry;
using BPEntity = FarmingApi.Modules.BusinessPartners.BusinessPartnersMaster.BusinessPartnersMaster;

namespace FarmingApi.Modules.SaleAR.ARReserveInvoice;

public interface IARReserveInvoiceJournalService
{
    JournalEntry CreateJournalEntry(ARReserveInvoice reserveInvoice, BPEntity customer);
}

public class ARReserveInvoiceJournalService : IARReserveInvoiceJournalService
{
    private readonly MyDbContext _db;

    public ARReserveInvoiceJournalService(MyDbContext db)
    {
        _db = db;
    }

    /// <summary>Pick the first non-empty account code from a list of candidates.</summary>
    private static string? FirstNonEmpty(params string?[] values)
        => values.FirstOrDefault(v => !string.IsNullOrWhiteSpace(v));

    public JournalEntry CreateJournalEntry(ARReserveInvoice reserveInvoice, BPEntity customer)
    {
        var gl = _db.Set<GLAccountDetermination>().FirstOrDefault()
                 ?? throw new InvalidOperationException(
                     "GL Account Determination (KGLD) not configured. " +
                     "Go to Administration → GL Account Determination and add " +
                     "ARControlAccount, RevenueAccount, TaxOutputAccount.");

        // Prefer the BP-level AR control account, fall back to the KGLD new field,
        // then the legacy field the GL Account Determination screen actually writes.
        var arCode = FirstNonEmpty(customer.ARControlAccount, gl.ARControlAccount, gl.AccountsReceivable);
        var revenueCode = FirstNonEmpty(gl.RevenueAccount, gl.SalesRevenue);
        var taxCode     = FirstNonEmpty(gl.TaxOutputAccount, gl.SalesTax);

        if (string.IsNullOrWhiteSpace(arCode))
            throw new InvalidOperationException(
                "AR Control Account not set — configure it in KGLD or on the Business Partner.");
        if (string.IsNullOrWhiteSpace(revenueCode))
            throw new InvalidOperationException(
                "Revenue Account not set in GL Account Determination (KGLD).");

        var grandTotal = reserveInvoice.Total;
        var taxAmount  = reserveInvoice.TaxAmount;
        var netRevenue = grandTotal - taxAmount;

        if (grandTotal <= 0)
            throw new InvalidOperationException(
                $"Cannot post AR Reserve Invoice {reserveInvoice.DocNum}: total is {grandTotal}");

        var postingDate = reserveInvoice.PostingDate ?? DateTime.UtcNow;

        var je = new JournalEntry
        {
            JrnlNo          = JournalEntryNumberService.Next(_db, postingDate),
            TransDate       = postingDate,
            DueDate         = reserveInvoice.DueDate ?? postingDate,
            DocDate         = postingDate,
            RefNo           = reserveInvoice.DocNum,
            Memo            = $"AR Reserve Invoice {reserveInvoice.DocNum} - {customer.CardName}",
            TransType       = "ARRI",
            BaseDocEntry    = reserveInvoice.Id,
            BaseDocType     = "KARI",
            Currency        = "USD",
            ExchangeRate    = 1,
            TotalDebit      = 0,
            TotalCredit     = 0,
            TotalFC         = 0,
            TotalLC         = 0,
            Status          = "O",
            IsAutoGenerated = true,
            VersionNum      = 1,
            CreatedAt       = DateTime.UtcNow,
            InActive        = false,
        };

        int lineNum = 1;

        // Dr Accounts Receivable — the full amount the customer owes (incl. tax)
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = arCode,
            AccountName = "Accounts Receivable",
            CardCode    = customer.Code,
            CardName    = customer.CardName,
            Debit       = grandTotal,
            Credit      = 0,
            DebitLC     = grandTotal,
            CreditLC    = 0,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Accounts Receivable — {reserveInvoice.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        // Cr Sales Revenue — net of tax
        je.Lines.Add(new JournalEntryLine
        {
            LineNum     = lineNum++,
            AccountCode = revenueCode,
            AccountName = "Sales Revenue",
            CardCode    = null,
            CardName    = null,
            Debit       = 0,
            Credit      = netRevenue,
            DebitLC     = 0,
            CreditLC    = netRevenue,
            DebitFC     = 0,
            CreditFC    = 0,
            LineMemo    = $"Revenue — {reserveInvoice.DocNum}",
            TaxAmount   = 0,
            CreatedAt   = DateTime.UtcNow,
            InActive    = false,
        });

        // Cr Output VAT — only when there is tax
        if (taxAmount > 0)
        {
            if (string.IsNullOrWhiteSpace(taxCode))
                throw new InvalidOperationException(
                    "Invoice has tax but Tax Output Account is not set in KGLD.");

            je.Lines.Add(new JournalEntryLine
            {
                LineNum     = lineNum++,
                AccountCode = taxCode,
                AccountName = "Output VAT",
                CardCode    = null,
                CardName    = null,
                Debit       = 0,
                Credit      = taxAmount,
                DebitLC     = 0,
                CreditLC    = taxAmount,
                DebitFC     = 0,
                CreditFC    = 0,
                LineMemo    = $"Output VAT — {reserveInvoice.DocNum}",
                TaxAmount   = taxAmount,
                CreatedAt   = DateTime.UtcNow,
                InActive    = false,
            });
        }

        var totalDr = je.Lines.Sum(l => l.Debit);
        var totalCr = je.Lines.Sum(l => l.Credit);
        if (Math.Abs(totalDr - totalCr) > 0.01m)
            throw new InvalidOperationException(
                $"Journal entry unbalanced: Dr={totalDr:N2} Cr={totalCr:N2}. " +
                $"Check invoice Total ({grandTotal}) vs TaxAmount ({taxAmount}).");

        je.TotalDebit  = totalDr;
        je.TotalCredit = totalCr;
        je.TotalLC     = totalDr;
        je.TotalFC     = 0;

        _db.Set<JournalEntry>().Add(je);
        return je;
    }
}
